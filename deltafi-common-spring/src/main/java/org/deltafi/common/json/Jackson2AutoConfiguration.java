package org.deltafi.common.json;

import com.fasterxml.jackson.databind.DeserializationFeature;
import com.fasterxml.jackson.databind.MapperFeature;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.SerializationFeature;
import com.fasterxml.jackson.databind.json.JsonMapper;
import com.fasterxml.jackson.datatype.jsr310.JavaTimeModule;
import org.springframework.boot.autoconfigure.AutoConfiguration;
import org.springframework.boot.autoconfigure.condition.ConditionalOnClass;
import org.springframework.boot.autoconfigure.condition.ConditionalOnMissingBean;
import org.springframework.context.annotation.Bean;

/**
 * Provides a Jackson 2 {@link ObjectMapper} bean. Spring Boot 4 ships only a Jackson 3
 * {@code JsonMapper} via autoconfig; consumers that still rely on Jackson 2's
 * {@code com.fasterxml.jackson.databind.ObjectMapper} can autowire the bean defined here.
 * Apps using HTTP JSON conversion should set {@code spring.http.converters.preferred-json-mapper=jackson}
 * so Spring registers {@code MappingJackson2HttpMessageConverter} using this bean.
 */
@AutoConfiguration
@ConditionalOnClass(ObjectMapper.class)
public class Jackson2AutoConfiguration {

    @Bean
    @ConditionalOnMissingBean
    public ObjectMapper objectMapper() {
        return JsonMapper.builder()
                .addModule(new JavaTimeModule())
                .disable(SerializationFeature.WRITE_DATES_AS_TIMESTAMPS)
                .disable(DeserializationFeature.FAIL_ON_UNKNOWN_PROPERTIES)
                .disable(MapperFeature.DEFAULT_VIEW_INCLUSION)
                .build();
    }
}
