// LintPlugin runs static checks against an existing Java plugin and returns
// a list of issues sorted by severity then file. A non-nil error indicates
// the lint run itself could not be performed (e.g. directory missing).
func (g *JavaGenerator) LintPlugin(pluginName string, options *generator.LintOptions) ([]generator.LintIssue, error) {
	dirOverride := ""
	if options != nil {
		dirOverride = options.PluginDir
	}
	pluginDir, err := resolvePluginDir(pluginName, dirOverride)
	if err != nil {
		return nil, err
	}
	if _, err := os.Stat(pluginDir); os.IsNotExist(err) {
		return nil, fmt.Errorf("plugin directory does not exist: %s", pluginDir)
	}

	var issues []generator.LintIssue
	issues = append(issues, lintJavaRequiredFiles(pluginDir)...)

	groupID, gradleIssues := lintBuildGradle(pluginDir)
	issues = append(issues, gradleIssues...)

	registeredActions, actionIssues := lintJavaActions(pluginDir, groupID)
	issues = append(issues, actionIssues...)

	issues = append(issues, lintJavaFlows(pluginDir, registeredActions)...)

	sort.SliceStable(issues, func(i, j int) bool {
		if issues[i].Severity != issues[j].Severity {
			return issues[i].Severity > issues[j].Severity
		}
		return issues[i].File < issues[j].File
	})
	return issues, nil
}

// javaRequiredFiles is the scaffolding every Java plugin must have. The
// gradle wrapper jar is binary and not regenerated by `plugin generate`,
// so it's marked optional (warning) rather than required.
var javaRequiredFiles = []struct {
	path     string
	optional bool
}{
	{path: "build.gradle"},
	{path: "settings.gradle"},
	{path: "gradle.properties"},
	{path: "gradlew"},
	{path: "gradlew.bat"},
	{path: "gradle/wrapper/gradle-wrapper.properties"},
	{path: "gradle/wrapper/gradle-wrapper.jar", optional: true},
	{path: ".gitignore"},
	{path: "src/main/resources/application.yaml"},
	{path: "README.md", optional: true},
	{path: "HEADER", optional: true},
	{path: "LICENSE", optional: true},
}

func lintJavaRequiredFiles(pluginDir string) []generator.LintIssue {
	var issues []generator.LintIssue
	for _, f := range javaRequiredFiles {
		if _, err := os.Stat(filepath.Join(pluginDir, f.path)); os.IsNotExist(err) {
			sev := generator.LintError
			if f.optional {
				sev = generator.LintWarning
			}
			issues = append(issues, generator.LintIssue{
				Severity: sev,
				File:     f.path,
				Message:  "required file missing",
			})
		}
	}
	return issues
}

var (
	gradleGroupRe   = regexp.MustCompile(`(?m)^group\s+['"]([^'"]+)['"]`)
	gradlePluginRe  = regexp.MustCompile(`id\s+['"]org\.deltafi\.plugin-convention['"]`)
	gradleActionKit = "org.deltafi.actionkit"
)

// lintBuildGradle parses build.gradle and returns the declared group ID
// (used to locate the plugin class and actions on disk) plus any issues.
func lintBuildGradle(pluginDir string) (string, []generator.LintIssue) {
	var issues []generator.LintIssue
	gradlePath := filepath.Join(pluginDir, "build.gradle")
	content, err := os.ReadFile(gradlePath)
	if err != nil {
		// Required-files check already reports missing build.gradle.
		return "", nil
	}
	src := string(content)

	groupID := ""
	if m := gradleGroupRe.FindStringSubmatch(src); len(m) >= 2 {
		groupID = m[1]
	} else {
		issues = append(issues, generator.LintIssue{
			Severity: generator.LintError,
			File:     "build.gradle",
			Message:  "missing or unparseable group declaration (e.g. group 'org.example.myplugin')",
		})
	}

	if !gradlePluginRe.MatchString(src) {
		issues = append(issues, generator.LintIssue{
			Severity: generator.LintError,
			File:     "build.gradle",
			Message:  "missing required plugin id 'org.deltafi.plugin-convention' (the convention pulls in deltafi-actionkit and configures the build)",
		})
	}

	// `org.deltafi.actionkit` should NOT be declared as a direct dependency —
	// the plugin convention provides it. A direct declaration usually means a
	// stale build.gradle that pre-dates the convention plugin.
	if strings.Contains(src, gradleActionKit) {
		issues = append(issues, generator.LintIssue{
			Severity: generator.LintWarning,
			File:     "build.gradle",
			Message:  "build.gradle references " + gradleActionKit + " directly; the org.deltafi.plugin-convention plugin already provides it as a dependency",
		})
	}

	// gradle.properties should declare deltafiVersion. We don't enforce a
	// specific value, just that something is set.
	propsPath := filepath.Join(pluginDir, "gradle.properties")
	if propsContent, err := os.ReadFile(propsPath); err == nil {
		if !strings.Contains(string(propsContent), "deltafiVersion") {
			issues = append(issues, generator.LintIssue{
				Severity: generator.LintError,
				File:     "gradle.properties",
				Message:  "missing deltafiVersion property (used by the plugin convention to pin the action kit version)",
			})
		}
	}

	return groupID, issues
}

var (
	javaPackageRe   = regexp.MustCompile(`(?m)^package\s+([\w.]+)\s*;`)
	javaClassRe     = regexp.MustCompile(`(?m)^public\s+class\s+(\w+)`)
	javaComponentRe = regexp.MustCompile(`@Component\b`)
	javaExtendsRe   = regexp.MustCompile(`extends\s+(\w+)`)
	javaSpringBoot  = regexp.MustCompile(`@SpringBootApplication\b`)
)

// javaActionBaseClasses is the set of action-kit base classes that mark a
// Java class as a registerable action. Anything in src/main/java/.../actions
// that does not extend one of these is flagged.
var javaActionBaseClasses = map[string]bool{
	"TransformAction":    true,
	"EgressAction":       true,
	"TimedIngressAction": true,
}

// lintJavaActions walks src/main/java for the plugin Spring Boot main class
// and any action classes. Returns the set of registered action class names
// (used by the flow JSON check) plus issues found.
func lintJavaActions(pluginDir, groupID string) (map[string]bool, []generator.LintIssue) {
	registered := map[string]bool{}
	var issues []generator.LintIssue

	javaSrc := filepath.Join(pluginDir, "src", "main", "java")
	if _, err := os.Stat(javaSrc); os.IsNotExist(err) {
		return registered, []generator.LintIssue{{
			Severity: generator.LintError,
			File:     filepath.Join("src", "main", "java"),
			Message:  "missing src/main/java source root",
		}}
	}

	// Walk every .java file under src/main/java once. We classify each as
	// (a) the plugin's Spring Boot main class, (b) an action under
	// .../actions/, or (c) other (lookup table suppliers, helper classes,
	// parameter POJOs).
	hasSpringBootMain := false
	expectedPackagePrefix := groupID
	mismatchedPackages := []string{}

	err := filepath.WalkDir(javaSrc, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || !strings.HasSuffix(d.Name(), ".java") {
			return nil
		}
		rel, _ := filepath.Rel(pluginDir, path)
		content, readErr := os.ReadFile(path)
		if readErr != nil {
			issues = append(issues, generator.LintIssue{
				Severity: generator.LintError,
				File:     rel,
				Message:  fmt.Sprintf("failed to read file: %v", readErr),
			})
			return nil
		}
		src := string(content)

		// Package vs declared groupID consistency check.
		if expectedPackagePrefix != "" {
			if pm := javaPackageRe.FindStringSubmatch(src); len(pm) >= 2 {
				if !strings.HasPrefix(pm[1], expectedPackagePrefix) {
					mismatchedPackages = append(mismatchedPackages, fmt.Sprintf("%s (package=%s)", rel, pm[1]))
				}
			}
		}

		// Spring Boot main class
		if javaSpringBoot.MatchString(src) {
			hasSpringBootMain = true
		}

		// Actions live under .../actions/
		if !strings.Contains(rel, string(os.PathSeparator)+"actions"+string(os.PathSeparator)) {
			return nil
		}

		className := ""
		if cm := javaClassRe.FindStringSubmatch(src); len(cm) >= 2 {
			className = cm[1]
		}
		// Skip parameter POJOs and helper classes that happen to live in actions/.
		// We only flag classes that look like they're meant to be actions.
		extendsBase := ""
		if em := javaExtendsRe.FindStringSubmatch(src); len(em) >= 2 {
			extendsBase = em[1]
		}
		if !javaActionBaseClasses[extendsBase] {
			return nil
		}

		// This is an action. It must have @Component to be picked up by Spring.
		if !javaComponentRe.MatchString(src) {
			issues = append(issues, generator.LintIssue{
				Severity: generator.LintError,
				File:     rel,
				Message:  fmt.Sprintf("action class %s extends %s but is missing @Component (Spring will not register it)", className, extendsBase),
			})
		}

		if className != "" {
			registered[className] = true
		}
		return nil
	})
	if err != nil {
		issues = append(issues, generator.LintIssue{
			Severity: generator.LintError,
			File:     filepath.Join("src", "main", "java"),
			Message:  fmt.Sprintf("failed to walk Java sources: %v", err),
		})
	}

	if !hasSpringBootMain {
		issues = append(issues, generator.LintIssue{
			Severity: generator.LintError,
			File:     filepath.Join("src", "main", "java"),
			Message:  "no @SpringBootApplication class found (the plugin must have a Spring Boot bootstrap class)",
		})
	}

	if len(mismatchedPackages) > 0 {
		issues = append(issues, generator.LintIssue{
			Severity: generator.LintWarning,
			File:     filepath.Join("src", "main", "java"),
			Message:  fmt.Sprintf("Java classes with package not matching build.gradle group %q: %s", expectedPackagePrefix, strings.Join(mismatchedPackages, ", ")),
		})
	}

	return registered, issues
}

// flowActionFields lists the keys in a flow JSON document whose values
// (objects or arrays of objects) describe action references via a "type" field.
var flowActionFields = []string{
	"transformActions",
	"egressAction",
	"timedIngressAction",
	"ingressAction",
	"loadActions",
	"formatActions",
	"validateActions",
	"enrichActions",
	"domainActions",
	"errorAction",
}

// lintJavaFlows scans src/main/resources/flows/*.json for action references
// and verifies each one resolves to a class registered in this plugin.
func lintJavaFlows(pluginDir string, registered map[string]bool) []generator.LintIssue {
	var issues []generator.LintIssue
	dir := filepath.Join(pluginDir, "src", "main", "resources", "flows")
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil
	}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".json") || e.Name() == "variables.json" {
			continue
		}
		relPath := filepath.Join("src", "main", "resources", "flows", e.Name())
		content, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			issues = append(issues, generator.LintIssue{
				Severity: generator.LintError,
				File:     relPath,
				Message:  fmt.Sprintf("failed to read file: %v", err),
			})
			continue
		}
		var doc map[string]any
		if err := json.Unmarshal(content, &doc); err != nil {
			issues = append(issues, generator.LintIssue{
				Severity: generator.LintError,
				File:     relPath,
				Message:  fmt.Sprintf("invalid JSON: %v", err),
			})
			continue
		}
		for _, field := range flowActionFields {
			refs := extractActionTypeRefs(doc[field])
			for _, ref := range refs {
				class := ref
				if i := strings.LastIndex(ref, "."); i >= 0 {
					class = ref[i+1:]
				}
				if !registered[class] && !registered[ref] {
					issues = append(issues, generator.LintIssue{
						Severity: generator.LintWarning,
						File:     relPath,
						Message:  fmt.Sprintf("references action %q which is not registered in this plugin (may be provided by another plugin)", ref),
					})
				}
			}
		}
	}
	return issues
}

// extractActionTypeRefs walks an action-bearing field (an object or array of
// objects) and returns the values of every "type" key it finds.
func extractActionTypeRefs(node any) []string {
	if node == nil {
		return nil
	}
	var refs []string
	switch v := node.(type) {
	case map[string]any:
		if t, ok := v["type"].(string); ok && t != "" {
			refs = append(refs, t)
		}
	case []any:
		for _, item := range v {
			refs = append(refs, extractActionTypeRefs(item)...)
		}
	}
	return refs
}
