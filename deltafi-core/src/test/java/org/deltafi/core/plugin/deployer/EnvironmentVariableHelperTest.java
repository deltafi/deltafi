package org.deltafi.core.plugin.deployer;

import org.deltafi.common.action.EventQueueProperties;
import org.deltafi.common.content.StorageProperties;
import org.deltafi.common.storage.s3.minio.MinioProperties;
import org.deltafi.common.types.KeyValue;
import org.deltafi.core.services.SslConfigService;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.mockito.Mockito;
import org.springframework.core.env.Environment;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

class EnvironmentVariableHelperTest {

    @TempDir
    Path tempDir;

    private final EnvironmentVariableHelper environmentVariableHelper;

    EnvironmentVariableHelperTest() {
        SslConfigService sslConfigService = Mockito.mock(SslConfigService.class);
        Environment env = Mockito.mock(Environment.class);
        this.environmentVariableHelper = new EnvironmentVariableHelper(new MinioProperties(), new StorageProperties("bucket"),
                sslConfigService, new EventQueueProperties(), env);
    }

    @Test
    void readPluginEnvVars_parsesKeyValueLines() throws IOException {
        Path file = tempDir.resolve("plugin.env");
        Files.writeString(file, "FOO=bar\nBAZ=qux\n");

        List<KeyValue> result = environmentVariableHelper.readPluginEnvVars(file);

        assertThat(result).hasSize(2);
        assertThat(result.get(0).getKey()).isEqualTo("FOO");
        assertThat(result.get(0).getValue()).isEqualTo("bar");
        assertThat(result.get(1).getKey()).isEqualTo("BAZ");
        assertThat(result.get(1).getValue()).isEqualTo("qux");
    }

    @Test
    void readPluginEnvVars_returnsEmptyForMissingFile() {
        List<KeyValue> result = environmentVariableHelper.readPluginEnvVars(tempDir.resolve("nonexistent"));

        assertThat(result).isEmpty();
    }

    @Test
    void readPluginEnvVars_returnsEmptyForEmptyFile() throws IOException {
        Path file = tempDir.resolve("plugin.env");
        Files.writeString(file, "");

        List<KeyValue> result = environmentVariableHelper.readPluginEnvVars(file);

        assertThat(result).isEmpty();
    }

    @Test
    void readPluginEnvVars_skipsCommentsAndBlankLines() throws IOException {
        Path file = tempDir.resolve("plugin.env");
        Files.writeString(file, "# Generated by deltafi\n\nFOO=bar\n\n# another comment\nBAZ=qux\n");

        List<KeyValue> result = environmentVariableHelper.readPluginEnvVars(file);

        assertThat(result).hasSize(2);
        assertThat(result.get(0).getKey()).isEqualTo("FOO");
        assertThat(result.get(1).getKey()).isEqualTo("BAZ");
    }

    @Test
    void readPluginEnvVars_handlesValuesWithEquals() throws IOException {
        Path file = tempDir.resolve("plugin.env");
        Files.writeString(file, "CONNECTION=host=db port=5432\n");

        List<KeyValue> result = environmentVariableHelper.readPluginEnvVars(file);

        assertThat(result).hasSize(1);
        assertThat(result.getFirst().getKey()).isEqualTo("CONNECTION");
        assertThat(result.getFirst().getValue()).isEqualTo("host=db port=5432");
    }

    @Test
    void readPluginEnvVars_handlesEmptyValue() throws IOException {
        Path file = tempDir.resolve("plugin.env");
        Files.writeString(file, "EMPTY=\n");

        List<KeyValue> result = environmentVariableHelper.readPluginEnvVars(file);

        assertThat(result).hasSize(1);
        assertThat(result.getFirst().getKey()).isEqualTo("EMPTY");
        assertThat(result.getFirst().getValue()).isEmpty();
    }
}
