package org.deltafi.gradle.license

/**
 * Renders the HEADER content into a language-appropriate comment block and detects an existing
 * leading comment block of the same style so it can be replaced. Output bytes match the prior
 * hierynomus.license formatter so the swap-over is a no-op against already-licensed files.
 */
class CommentStyle {
    static final String SLASHSTAR_STYLE = 'SLASHSTAR_STYLE'
    static final String SCRIPT_STYLE = 'SCRIPT_STYLE'

    static String render(String style, List<String> headerLines) {
        if (style == SLASHSTAR_STYLE) {
            StringBuilder sb = new StringBuilder('/*\n')
            for (String line : headerLines) {
                sb.append(line.isEmpty() ? ' *\n' : ' * ' + line + '\n')
            }
            sb.append(' */\n')
            return sb.toString()
        }
        if (style == SCRIPT_STYLE) {
            StringBuilder sb = new StringBuilder('#\n')
            for (String line : headerLines) {
                sb.append(line.isEmpty() ? '#\n' : '# ' + line + '\n')
            }
            sb.append('#\n')
            return sb.toString()
        }
        throw new IllegalArgumentException("Unsupported comment style: ${style}")
    }

    /**
     * Returns the end index (exclusive) of the leading shebang line, or 0 if the file has none.
     * Used so the license header can be inserted after the shebang rather than overwriting it.
     */
    static int shebangEnd(String content) {
        if (!content.startsWith('#!')) return 0
        int nl = content.indexOf('\n')
        return nl < 0 ? content.length() : nl + 1
    }

    /**
     * Returns true when the file is generated and exempt from header checks. Recognises the Go
     * {@code // Code generated ... DO NOT EDIT.} convention and the Java
     * {@code Code generated by ...} marker some codegen tools emit.
     */
    static boolean isGeneratedExempt(String content) {
        if (content.startsWith('// Code generated') && content.indexOf('DO NOT EDIT') >= 0) return true
        if (content.startsWith('/* Code generated') && content.indexOf('DO NOT EDIT') >= 0) return true
        return false
    }

    /**
     * Returns the end index (exclusive) of any leading line-comment block that should be skipped
     * before searching for a SLASHSTAR header. Handles Go build constraints
     * ({@code //go:build}, {@code // +build}) and ABOUTME-style `// ABOUTME:` comments that
     * intentionally precede the license header. Stops at the first blank line.
     */
    static int leadingLineCommentEnd(String style, String content, int start) {
        if (style != SLASHSTAR_STYLE) return start
        int idx = start
        int len = content.length()
        while (idx < len) {
            if (idx + 1 < len && content.charAt(idx) == '/' as char && content.charAt(idx + 1) == '/' as char) {
                int nl = content.indexOf('\n', idx)
                if (nl < 0) return len
                idx = nl + 1
                // Consume the blank line separator that conventionally follows.
                if (idx < len && content.charAt(idx) == '\n' as char) idx++
                continue
            }
            break
        }
        return idx
    }

    /**
     * Returns the end index (exclusive) of the leading header block — up to and including the
     * newline that terminates the closing comment marker. Whitespace lines after the header are
     * left in place so existing styling around the package/import block is preserved.
     * Returns -1 if no leading header block of this style is present.
     */
    static int existingHeaderEnd(String style, String content, int start) {
        if (style == SLASHSTAR_STYLE) {
            if (!content.startsWith('/*', start)) return -1
            int close = content.indexOf('*/', start)
            if (close < 0) return -1
            int after = close + 2
            if (after < content.length() && content.charAt(after) == '\n') after++
            return after
        }
        if (style == SCRIPT_STYLE) {
            if (start >= content.length() || content.charAt(start) != '#' as char) return -1
            int idx = start
            int len = content.length()
            while (idx < len) {
                if (content.charAt(idx) != '#' as char) break
                int nl = content.indexOf('\n', idx)
                if (nl < 0) { idx = len; break }
                idx = nl + 1
            }
            return idx
        }
        throw new IllegalArgumentException("Unsupported comment style: ${style}")
    }
}
